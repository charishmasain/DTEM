"""
dtem.collector.manager
~~~~~~~~~~~~~~~~~~~~~~

Orchestrates all registered threat intelligence collectors,
de‑duplicates results, persists records into the SQLite database,
and saves raw JSON output files.

Usage:
    from dtem.collector.manager import CollectorManager

    manager = CollectorManager()
    results = manager.collect("LockBit")
"""

import json
import logging
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from dtem.collector.base import BaseCollector
from dtem.collector.nvd_collector import NVDCollector
from dtem.collector.otx_collector import OTXCollector
from dtem.collector.darkweb import DarkWebCollector
from dtem.data.database import (
    get_or_create_query,
    insert_intel_records,
    init_db,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Load output config
# ---------------------------------------------------------------------------

_CONFIG_PATH = Path(__file__).resolve().parent.parent / "config.json"
_PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent


def _load_output_config() -> dict[str, str]:
    with open(_CONFIG_PATH, "r", encoding="utf-8") as fh:
        return json.load(fh).get("output", {})


class CollectorManager:
    """
    Central controller that runs all enabled collectors for a
    given keyword and unifies their output.
    """

    def __init__(self) -> None:
        init_db()
        self.collectors: list[BaseCollector] = [
            NVDCollector(),
            OTXCollector(),
            DarkWebCollector(),
        ]
        self._output_cfg = _load_output_config()

    # ------------------------------------------------------------------ #
    # Public API
    # ------------------------------------------------------------------ #

    def collect(self, keyword: str) -> list[dict[str, Any]]:
        """
        Run every registered collector for *keyword*, de‑duplicate,
        persist to DB, save JSON, and return the unified list.
        """
        keyword_lower = keyword.strip().lower()
        logger.info("=" * 60)
        logger.info("CollectorManager: collecting for '%s'", keyword_lower)
        logger.info("=" * 60)

        all_records: list[dict[str, Any]] = []

        for collector in self.collectors:
            try:
                logger.info("Running %s …", collector)
                records = collector.collect(keyword_lower)
                logger.info(
                    "%s returned %d records.", collector, len(records)
                )
                all_records.extend(records)
            except Exception as exc:
                logger.error(
                    "%s raised an exception: %s", collector, exc, exc_info=True
                )

        # De‑duplicate by (source + title) pair
        unique = self._deduplicate(all_records)
        logger.info(
            "Total records: %d (after dedup: %d)",
            len(all_records),
            len(unique),
        )

        # Persist to database (skip dark web records — already saved)
        self._persist(keyword_lower, unique)

        # Save JSON output
        self._save_json(keyword_lower, unique)

        return unique

    # ------------------------------------------------------------------ #
    # De‑duplication
    # ------------------------------------------------------------------ #

    @staticmethod
    def _deduplicate(
        records: list[dict[str, Any]],
    ) -> list[dict[str, Any]]:
        """
        Remove exact duplicates based on (source, title).
        Keeps the first occurrence.
        """
        seen: set[tuple[str, str]] = set()
        unique: list[dict[str, Any]] = []
        for rec in records:
            key = (rec.get("source", ""), rec.get("title", ""))
            if key not in seen:
                seen.add(key)
                unique.append(rec)
        return unique

    # ------------------------------------------------------------------ #
    # Persistence
    # ------------------------------------------------------------------ #

    def _persist(
        self,
        keyword: str,
        records: list[dict[str, Any]],
    ) -> None:
        """
        Insert records into the SQLite database.

        Dark web records generated by DarkWebCollector are already
        saved during collection, so we skip them here to avoid
        duplicates.
        """
        query_id = get_or_create_query(keyword)

        to_insert = []
        for rec in records:
            # Dark web simulator records already persisted
            if rec.get("source_type") == "dark_web":
                continue
            to_insert.append({**rec, "query_id": query_id})

        if to_insert:
            count = insert_intel_records(to_insert)
            logger.info("Persisted %d non‑dark‑web records to DB.", count)

    # ------------------------------------------------------------------ #
    # JSON output
    # ------------------------------------------------------------------ #

    def _save_json(
        self,
        keyword: str,
        records: list[dict[str, Any]],
    ) -> Path:
        """
        Write the collected records to a JSON file inside the
        configured output directory.

        Returns the path to the created file.
        """
        output_dir = _PROJECT_ROOT / self._output_cfg.get("json_dir", "output")
        output_dir.mkdir(parents=True, exist_ok=True)

        # Sanitise the keyword for use as a filename
        safe_name = keyword.replace(" ", "_").replace("/", "_")
        filename = f"{safe_name}_intel.json"
        filepath = output_dir / filename

        # Make records JSON‑serialisable (raw_data may already be a dict)
        serialisable = []
        for rec in records:
            item = dict(rec)
            rd = item.get("raw_data")
            if rd and not isinstance(rd, (dict, list, str)):
                item["raw_data"] = str(rd)
            serialisable.append(item)

        payload = {
            "keyword": keyword,
            "collected_at": datetime.now(timezone.utc).isoformat(),
            "total_records": len(serialisable),
            "records": serialisable,
        }

        with open(filepath, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, indent=2, default=str)

        logger.info("JSON output saved to %s", filepath)
        return filepath
